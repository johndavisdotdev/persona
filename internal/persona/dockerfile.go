type dockerfileData struct {
	GitAuth     string
	P           *Persona
	BaseImage   string
	AptPackages []string
	NeedsUV     bool
	MCPJSON     string
	ClaudeMD    string
	Entrypoint  string
	Skills      []skillCmd
}

type skillCmd struct{ Name, Repo, Path, Ref string }

var funcs = template.FuncMap{"shq": shellQuote}

var dockerfileTmpl = template.Must(template.New("Dockerfile").Funcs(funcs).Parse(`# syntax=docker/dockerfile:1
# ------------------------------------------------------------------------------
# persona: {{.P.Name}}
# Generated by ` + "`persona`" + `. This file is the precise definition of the persona's
# image. Edit it freely with ` + "`persona edit {{.P.Name}}`" + `; once hand-edited,
# ` + "`persona update`" + ` will not overwrite it without --force.
# ------------------------------------------------------------------------------
FROM {{.BaseImage}}

LABEL persona.managed="true" \
      persona.name="{{.P.Name}}"

ENV DEBIAN_FRONTEND=noninteractive \
    LANG=C.UTF-8 \
    TERM=xterm-256color \
    PERSONA_NAME={{.P.Name}}

RUN apt-get update \
 && apt-get install -y --no-install-recommends \
{{- range .AptPackages}}
      {{.}} \
{{- end}}
 && rm -rf /var/lib/apt/lists/*
{{if .NeedsUV}}
# uv / uvx for Python-based MCP servers
RUN curl -LsSf https://astral.sh/uv/install.sh | env UV_INSTALL_DIR=/usr/local/bin UV_NO_MODIFY_PATH=1 sh
{{end}}
RUN useradd --create-home --shell /bin/bash --uid 1000 claude \
 && mkdir -p /workspace \
 && chown claude:claude /workspace

USER claude
WORKDIR /home/claude
ENV PATH=/home/claude/.local/bin:$PATH

# Claude Code (native installer)
RUN curl -fsSL https://claude.ai/install.sh | bash \
 && claude --version

# Persona instructions (user memory).
COPY --chown=claude:claude <<'PERSONA_CLAUDE_MD' /home/claude/.claude/CLAUDE.md
{{.ClaudeMD}}
PERSONA_CLAUDE_MD

# MCP servers, merged into ~/.claude.json at user scope below.
COPY --chown=claude:claude <<'PERSONA_MCP' /home/claude/.persona/mcp.json
{{.MCPJSON}}
PERSONA_MCP

# Claude Code user settings (the persona's settings.json, generated by persona
# from base-settings.json + base + persona; edit with: persona edit NAME --settings).
COPY --chown=claude:claude settings.json /home/claude/.claude/settings.json

# Pre-install every marketplace and enabled plugin declared in settings.json.
# Failures are non-fatal: Claude Code retries declared plugins on first launch.
# Private GitHub repos use the optional github_token build secret (never stored in a layer).
RUN --mount=type=secret,id=github_token,env=GITHUB_TOKEN,uid=1000 \
    {{.GitAuth}} \
    s=/home/claude/.claude/settings.json; \
    jq -r '.extraKnownMarketplaces // {} | to_entries[] | .value.source | (.repo // .url // .path // empty)' "$s" \
    | while read -r src; do \
        claude plugin marketplace add "$src" || echo "persona: warning: could not add marketplace $src" >&2; \
      done; \
    jq -r '.enabledPlugins // {} | to_entries[] | select(.value == true) | .key' "$s" \
    | while read -r id; do \
        claude plugin install "$id" --scope user || echo "persona: warning: could not pre-install $id" >&2; \
      done
{{- if .Skills}}
# Standalone skills.
{{- range .Skills}}
RUN --mount=type=secret,id=github_token,env=GITHUB_TOKEN,uid=1000 \
    {{$.GitAuth}} \
    git clone --depth 1 {{if .Ref}}--branch {{shq .Ref}} {{end}}{{shq .Repo}} /tmp/skill-src \
 && mkdir -p /home/claude/.claude/skills \
 && cp -R /tmp/skill-src/{{.Path}} /home/claude/.claude/skills/{{.Name}} \
 && rm -rf /tmp/skill-src
{{- end}}
{{end}}
# Skip onboarding, pre-trust /workspace, and register MCP servers.
RUN f=/home/claude/.claude.json; [ -s "$f" ] || echo '{}' > "$f"; \
    jq --slurpfile mcp /home/claude/.persona/mcp.json \
      '.hasCompletedOnboarding = true | .bypassPermissionsModeAccepted = true | .projects["/workspace"].hasTrustDialogAccepted = true | .projects["/workspace"].hasCompletedProjectOnboarding = true | .mcpServers = ((.mcpServers // {}) + $mcp[0])' \
      "$f" > "$f.tmp" \
 && mv "$f.tmp" "$f"

COPY --chown=claude:claude --chmod=0755 <<'PERSONA_ENTRYPOINT' /home/claude/.local/bin/persona-entrypoint
{{.Entrypoint}}
PERSONA_ENTRYPOINT

WORKDIR /workspace
ENTRYPOINT ["/home/claude/.local/bin/persona-entrypoint"]
`))

// gitAuth rewrites GitHub URLs to use the build secret, via env-only git config
// that lives for a single RUN step.
const gitAuth = `if [ -n "${GITHUB_TOKEN:-}" ]; then export GIT_CONFIG_COUNT=1 GIT_CONFIG_KEY_0="url.https://x-access-token:${GITHUB_TOKEN}@github.com/.insteadOf" GIT_CONFIG_VALUE_0="https://github.com/"; fi;`

// entrypoint starts Claude Code inside a detached tmux session so that
// `persona join` and the control center can attach to it at any time.
const entrypoint = `#!/bin/sh
set -eu
# Any explicit command bypasses the session (e.g. docker run IMAGE bash).
if [ "$#" -gt 0 ]; then exec "$@"; fi

# Pre-approve a forwarded API key so Claude Code does not prompt for it.
if [ -n "${ANTHROPIC_API_KEY:-}" ]; then
  f="$HOME/.claude.json"
  tail=$(printf %s "$ANTHROPIC_API_KEY" | tail -c 20)
  jq --arg k "$tail" '.customApiKeyResponses.approved = (((.customApiKeyResponses.approved // []) + [$k]) | unique)' "$f" > "$f.tmp" && mv "$f.tmp" "$f"
fi

tmux -u new-session -d -s ` + SessionName + ` -x "${PERSONA_COLS:-200}" -y "${PERSONA_ROWS:-50}" \
  'if [ -n "${PERSONA_PROMPT:-}" ]; then claude ${PERSONA_CLAUDE_ARGS:-} "$PERSONA_PROMPT"; else claude ${PERSONA_CLAUDE_ARGS:-}; fi; echo; echo "[claude exited - shell kept open]"; exec bash -l'
tmux set-option -t ` + SessionName + ` status-left "[${PERSONA_NAME:-persona}] " >/dev/null
tmux set-option -t ` + SessionName + ` status-left-length 40 >/dev/null

trap 'tmux kill-server 2>/dev/null; exit 0' TERM INT
while tmux has-session -t ` + SessionName + ` 2>/dev/null; do sleep 1; done`

// RenderDockerfile produces the Dockerfile for a persona, with the base
// requirements (base.yaml) merged in.
func RenderDockerfile(p *Persona) (string, error) {
	p.Normalize()
	base, err := LoadBase()
	if err != nil {
		return "", err
	}
	return renderDockerfile(Effective(p, base))
}

func renderDockerfile(p *Persona) (string, error) {
	base := p.BaseImage
	if base == "" {
		base = viper.GetString(config.KeyBaseImage)
	}

	// rsync copies workspaces into microVM instances.
	apt := []string{"ca-certificates", "curl", "git", "jq", "less", "procps", "ripgrep", "rsync", "tmux"}
	needsUV := false
	for _, s := range p.MCPServers {
		switch path.Base(s.Command) {
		case "npx", "node", "npm":
			apt = append(apt, "nodejs", "npm")
		case "uvx", "uv":
			needsUV = true
		case "python", "python3", "pip", "pip3":
			apt = append(apt, "python3", "python3-pip", "python3-venv")
		}
	}
	apt = append(apt, p.AptPackages...)
	apt = dedupe(apt)
	sort.Strings(apt)

	mcp, err := mcpJSON(p)
	if err != nil {
		return "", err
	}

	data := dockerfileData{
		P:           p,
		BaseImage:   base,
		AptPackages: apt,
		NeedsUV:     needsUV,
		MCPJSON:     mcp,
		ClaudeMD:    claudeMD(p),
		Entrypoint:  entrypoint,
		GitAuth:     gitAuth,
	}
	for _, s := range p.Skills {
		sp := strings.Trim(path.Clean("/"+s.Path), "/")
		if sp == "" {
			sp = "."
		}
		data.Skills = append(data.Skills, skillCmd{Name: s.Name, Repo: gitURL(s.Repo), Path: shellQuote(sp), Ref: s.Ref})
	}

	for _, block := range []string{data.MCPJSON, data.ClaudeMD} {
		for _, delim := range []string{"PERSONA_CLAUDE_MD", "PERSONA_MCP", "PERSONA_ENTRYPOINT"} {
			if strings.Contains(block, "\n"+delim+"\n") || strings.HasPrefix(block, delim+"\n") {
				return "", fmt.Errorf("persona content contains reserved heredoc delimiter %s", delim)
			}
		}
	}

	var buf bytes.Buffer
	if err := dockerfileTmpl.Execute(&buf, data); err != nil {
		return "", err
	}
	return buf.String(), nil
}

func mcpJSON(p *Persona) (string, error) {
	servers := map[string]any{}
	for _, s := range p.MCPServers {
		entry := map[string]any{"type": s.Type}
		if s.Type == "stdio" {
			entry["command"] = s.Command
			entry["args"] = nonNil(s.Args)
			if len(s.Env) > 0 {
				entry["env"] = s.Env
			}
		} else {
			entry["url"] = s.URL
			if len(s.Headers) > 0 {
				entry["headers"] = s.Headers
			}
		}
		servers[s.Name] = entry
	}
	b, err := json.MarshalIndent(servers, "", "  ")
	return string(b), err
}

func claudeMD(p *Persona) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Persona: %s\n\n", p.Name)
	if p.Summary != "" {
		b.WriteString(p.Summary + "\n\n")
	}
	if p.Instructions != "" {
		b.WriteString(strings.TrimSpace(p.Instructions) + "\n\n")
	}
	b.WriteString("You are running inside a persona container. The user's project, if any, is mounted at /workspace.\n")
	return b.String()
}

func marketplaceSource(src string) map[string]string {
	if strings.Contains(src, "://") || strings.HasSuffix(src, ".git") || strings.HasPrefix(src, "git@") {
		return map[string]string{"source": "git", "url": src}
	}
	return map[string]string{"source": "github", "repo": src}
}

func gitURL(repo string) string {
	if strings.Contains(repo, "://") || strings.HasPrefix(repo, "git@") {
		return repo
	}
	return "https://github.com/" + strings.TrimSuffix(repo, ".git") + ".git"
}

func nonNil(s []string) []string {
	if s == nil {
		return []string{}
	}
	return s
}

// shellQuote single-quotes s for POSIX sh.
func shellQuote(s string) string {
	if s != "" && strings.IndexFunc(s, func(r rune) bool {
		return !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || strings.ContainsRune("@%+=:,./-_", r))
	}) == -1 {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'"'"'`) + "'"
}
